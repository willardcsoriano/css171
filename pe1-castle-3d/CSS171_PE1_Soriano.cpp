// Load one image file into a mipmapped texture; returns 0 on failure
GLuint loadTexture(const TextureFile &file) {
    int width = 0, height = 0, channels = 0;
    // Image rows are stored top-first; OpenGL expects the bottom row first
    stbi_set_flip_vertically_on_load(true);
    unsigned char *pixels = stbi_load(file.path, &width, &height, &channels, STBI_rgb_alpha);
    if (pixels == nullptr) {
        std::cerr << "Failed to load texture '" << file.path << "': " << stbi_failure_reason()
                  << "\n(run the program from the folder that contains textures/)\n";
        return 0;
    }

    GLuint texture = 0;
    glGenTextures(1, &texture);
    glBindTexture(GL_TEXTURE_2D, texture);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, file.wrapMode);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, file.wrapMode);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_LINEAR_MIPMAP_LINEAR);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_LINEAR);
    // Rows of 4-byte RGBA pixels are always 4-byte aligned, the GL default
    glTexImage2D(GL_TEXTURE_2D, 0, GL_RGBA8, width, height, 0, GL_RGBA, GL_UNSIGNED_BYTE, pixels);
    glGenerateMipmap(GL_TEXTURE_2D);

    stbi_image_free(pixels);
    return texture;
}

// ------------------------------------------------------------------------------
// Castle construction (hierarchical modeling)
//
// Each builder receives its parent's transform and appends parts expressed
// relative to it. Transforms compose as parent * translate * rotate * scale.
// ------------------------------------------------------------------------------

// Append a box of the given size, centered at `center` in the parent's space
void addBox(std::vector<Part> &parts, const glm::mat4 &parent, glm::vec3 center, glm::vec3 size,
            TextureId texture, glm::vec3 tint = NO_TINT, float yawDegrees = 0.0f) {
    glm::mat4 transform = glm::translate(parent, center);
    transform = glm::rotate(transform, glm::radians(yawDegrees), glm::vec3(0, 1, 0));
    transform = glm::scale(transform, size);
    parts.push_back({ Shape::Box, texture, transform, size, tint, true, glm::vec2(1.0f) });
}

// Append a cylinder or cone standing on `base` (mesh UVs, tiled by texScale)
void addRound(std::vector<Part> &parts, const glm::mat4 &parent, Shape shape, glm::vec3 base,
              float radius, float height, TextureId texture, glm::vec2 texScale) {
    glm::vec3 size(radius * 2.0f, height, radius * 2.0f);
    glm::mat4 transform = glm::scale(glm::translate(parent, base), size);
    parts.push_back({ shape, texture, transform, size, NO_TINT, false, texScale });
}

// Row of merlons (battlement teeth) from `start` to `end` on a wall top.
// Pass includeEnd = false when the next row starts where this one ends, so
// the shared corner merlon is not drawn twice.
void addBattlement(std::vector<Part> &parts, const glm::mat4 &parent, glm::vec3 start, glm::vec3 end,
                   bool includeEnd = true) {
    glm::vec3 span = end - start;
    int count = (int)(glm::length(span) / MERLON_SPACING) + 1;
    int placed = (includeEnd || count == 1) ? count : count - 1;
    for (int i = 0; i < placed; ++i) {
        float t = (count == 1) ? 0.5f : (float)i / (count - 1);
        glm::vec3 position = start + span * t + glm::vec3(0.0f, MERLON_HEIGHT * 0.5f, 0.0f);
        addBox(parts, parent, position, glm::vec3(MERLON_SIZE, MERLON_HEIGHT, MERLON_SIZE), TEX_STONE);
    }
}

// Flag pole with a banner, standing on `base`
void addFlag(std::vector<Part> &parts, const glm::mat4 &parent, glm::vec3 base, float poleHeight) {
    const float POLE_WIDTH = 0.05f;
    const glm::vec3 BANNER_SIZE(0.62f, 0.38f, 0.03f);
    addBox(parts, parent, base + glm::vec3(0.0f, poleHeight * 0.5f, 0.0f),
           glm::vec3(POLE_WIDTH, poleHeight, POLE_WIDTH), TEX_WOOD, glm::vec3(0.55f));

    // The banner shows the whole banner image on its faces (no box mapping)
    glm::vec3 bannerCenter = base + glm::vec3(BANNER_SIZE.x * 0.5f + POLE_WIDTH * 0.5f,
                                              poleHeight - BANNER_SIZE.y * 0.5f, 0.0f);
    glm::mat4 transform = glm::scale(glm::translate(parent, bannerCenter), BANNER_SIZE);
    parts.push_back({ Shape::Box, TEX_BANNER, transform, BANNER_SIZE, NO_TINT, false, glm::vec2(1.0f) });
}

// Dark window recess on a wall; `yawDegrees` turns it to face outward
void addWindow(std::vector<Part> &parts, const glm::mat4 &parent, glm::vec3 center,
               glm::vec2 size, float yawDegrees) {
    const glm::vec3 WINDOW_TINT(0.10f, 0.09f, 0.08f);
    addBox(parts, parent, center, glm::vec3(size.x, size.y, 0.06f), TEX_STONE, WINDOW_TINT, yawDegrees);
}

// Round corner tower with slit window, conical roof and flag
void addTower(std::vector<Part> &parts, const glm::mat4 &castle, glm::vec3 base) {
    // The tower's own frame, turned so its local +Z faces away from the keep
    float outwardYaw = glm::degrees(std::atan2(base.x, base.z));
    glm::mat4 tower = glm::rotate(glm::translate(castle, base), glm::radians(outwardYaw), glm::vec3(0, 1, 0));

    const float stoneRepeatsAround = 3.0f; // bricks around the circumference
    addRound(parts, tower, Shape::Cylinder, glm::vec3(0.0f), TOWER_RADIUS, TOWER_HEIGHT, TEX_STONE,
             glm::vec2(stoneRepeatsAround, TOWER_HEIGHT * TEXTURE_REPEATS_PER_UNIT));
    addRound(parts, tower, Shape::Cone, glm::vec3(0.0f, TOWER_HEIGHT, 0.0f), TOWER_ROOF_RADIUS,
             TOWER_ROOF_HEIGHT, TEX_ROOF, glm::vec2(4.0f, 2.0f));
    addWindow(parts, tower, glm::vec3(0.0f, TOWER_HEIGHT * 0.62f, TOWER_RADIUS), glm::vec2(0.14f, 0.42f), 0.0f);
    addFlag(parts, tower, glm::vec3(0.0f, TOWER_HEIGHT + TOWER_ROOF_HEIGHT - 0.05f, 0.0f), 0.75f);
}

// Straight curtain wall between two tower centers, with battlements
void addCurtainWall(std::vector<Part> &parts, const glm::mat4 &castle, glm::vec3 from, glm::vec3 to) {
    glm::vec3 direction = to - from;
    float length = glm::length(direction);
    float yaw = glm::degrees(std::atan2(direction.z, direction.x));
    glm::mat4 wall = glm::rotate(glm::translate(castle, (from + to) * 0.5f), glm::radians(-yaw), glm::vec3(0, 1, 0));

    addBox(parts, wall, glm::vec3(0.0f, WALL_HEIGHT * 0.5f, 0.0f),
           glm::vec3(length, WALL_HEIGHT, WALL_THICKNESS), TEX_STONE);

    // Merlons on the outer edge only; the towers cover both wall ends
    float usable = length * 0.5f - TOWER_RADIUS - MERLON_SIZE;
    float outerEdge = WALL_THICKNESS * 0.5f - MERLON_SIZE * 0.5f;
    addBattlement(parts, wall, glm::vec3(-usable, WALL_HEIGHT, outerEdge), glm::vec3(usable, WALL_HEIGHT, outerEdge));
}

// Gatehouse on the front wall: raised block, wooden gate, path outward
void addGatehouse(std::vector<Part> &parts, const glm::mat4 &castle, glm::vec3 frontCenter) {
    const glm::vec3 BLOCK_SIZE(1.9f, 2.5f, 0.9f);
    const glm::vec3 GATE_SIZE(1.0f, 1.35f, 0.08f);
    glm::mat4 gatehouse = glm::translate(castle, frontCenter);

    addBox(parts, gatehouse, glm::vec3(0.0f, BLOCK_SIZE.y * 0.5f, 0.0f), BLOCK_SIZE, TEX_STONE);
    addBox(parts, gatehouse, glm::vec3(0.0f, GATE_SIZE.y * 0.5f, BLOCK_SIZE.z * 0.5f + GATE_SIZE.z * 0.5f),
           GATE_SIZE, TEX_WOOD);
    addWindow(parts, gatehouse, glm::vec3(0.0f, BLOCK_SIZE.y * 0.74f, BLOCK_SIZE.z * 0.5f), glm::vec2(0.5f, 0.28f), 0.0f);

    float halfWidth = BLOCK_SIZE.x * 0.5f - MERLON_SIZE * 0.5f;
    float frontEdge = BLOCK_SIZE.z * 0.5f - MERLON_SIZE * 0.5f;
    addBattlement(parts, gatehouse, glm::vec3(-halfWidth, BLOCK_SIZE.y, frontEdge),
                  glm::vec3(halfWidth, BLOCK_SIZE.y, frontEdge));

    // Dirt path from the gate to the island's rim: the rim point at the
    // path's outer corners (x = half width) lies at z = sqrt(R^2 - x^2)
    const float PATH_WIDTH = 1.1f;
    const float rimZ = std::sqrt(ISLAND_RADIUS * ISLAND_RADIUS - 0.25f * PATH_WIDTH * PATH_WIDTH);
    const float PATH_LENGTH = rimZ - (frontCenter.z + BLOCK_SIZE.z * 0.5f);
    addBox(parts, gatehouse, glm::vec3(0.0f, 0.005f, BLOCK_SIZE.z * 0.5f + PATH_LENGTH * 0.5f),
           glm::vec3(PATH_WIDTH, 0.01f, PATH_LENGTH), TEX_DIRT);
}

// Central keep: tall block with windows, battlements and a roofed turret
void addKeep(std::vector<Part> &parts, const glm::mat4 &castle) {
    const float half = KEEP_WIDTH * 0.5f;
    addBox(parts, castle, glm::vec3(0.0f, KEEP_HEIGHT * 0.5f, 0.0f),
           glm::vec3(KEEP_WIDTH, KEEP_HEIGHT, KEEP_WIDTH), TEX_STONE);

    // Two windows on each of the four faces, turned to face outward
    for (int side = 0; side < 4; ++side) {
        float yaw = 90.0f * side;
        glm::mat4 face = glm::rotate(castle, glm::radians(yaw), glm::vec3(0, 1, 0));
        for (float x : { -0.5f, 0.5f }) {
            addWindow(parts, face, glm::vec3(x, KEEP_HEIGHT * 0.66f, half), glm::vec2(0.28f, 0.5f), 0.0f);
        }
        // Battlement along this face's top outer edge; its end corner is the
        // next face's start corner, so each face leaves that merlon out
        float edge = half - MERLON_SIZE * 0.5f;
        addBattlement(parts, face, glm::vec3(-edge, KEEP_HEIGHT, edge), glm::vec3(edge, KEEP_HEIGHT, edge), false);
    }

    // Turret rising from the keep's roof
    const float TURRET_RADIUS = 0.5f;
    const float TURRET_HEIGHT = 1.1f;
    addRound(parts, castle, Shape::Cylinder, glm::vec3(0.0f, KEEP_HEIGHT, 0.0f), TURRET_RADIUS, TURRET_HEIGHT,
             TEX_STONE, glm::vec2(2.0f, TURRET_HEIGHT * TEXTURE_REPEATS_PER_UNIT));
    addRound(parts, castle, Shape::Cone, glm::vec3(0.0f, KEEP_HEIGHT + TURRET_HEIGHT, 0.0f), 0.68f, 1.2f,
             TEX_ROOF, glm::vec2(3.0f, 1.5f));
    addFlag(parts, castle, glm::vec3(0.0f, KEEP_HEIGHT + TURRET_HEIGHT + 1.15f, 0.0f), 0.95f);
}

// Build the complete castle in castle space (origin = island center, y = 0
// = ground level). The animated turntable rotation is applied at draw time.
std::vector<Part> buildCastle() {
    std::vector<Part> parts;
    const glm::mat4 castle(1.0f);
    const float s = WALL_HALF_SPAN;

    // Round island: an earth base topped by a thin grass layer whose top
    // surface is y = 0. Both reuse the cylinder mesh.
    const float EARTH_DEPTH = 0.5f;
    const float GRASS_DEPTH = 0.03f;
    const float islandRepeats = ISLAND_RADIUS * 2.0f * TEXTURE_REPEATS_PER_UNIT;
    addRound(parts, castle, Shape::Cylinder, glm::vec3(0.0f, -EARTH_DEPTH, 0.0f), ISLAND_RADIUS,
             EARTH_DEPTH - GRASS_DEPTH, TEX_DIRT, glm::vec2(12.0f, 0.5f));
    addRound(parts, castle, Shape::Cylinder, glm::vec3(0.0f, -GRASS_DEPTH, 0.0f), ISLAND_RADIUS,
             GRASS_DEPTH, TEX_GRASS, glm::vec2(islandRepeats));

    // Corner towers, clockwise from front-left as seen by the camera at start
    const glm::vec3 corners[] = { { -s, 0, s }, { s, 0, s }, { s, 0, -s }, { -s, 0, -s } };
    for (int i = 0; i < 4; ++i) {
        addCurtainWall(parts, castle, corners[i], corners[(i + 1) % 4]);
    }
    for (const glm::vec3 &corner : corners) {
        addTower(parts, castle, corner);
    }

    addGatehouse(parts, castle, glm::vec3(0.0f, 0.0f, s));
    addKeep(parts, castle);
    return parts;
}

