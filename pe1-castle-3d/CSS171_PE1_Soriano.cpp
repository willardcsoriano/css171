const char *VERTEX_SHADER_SOURCE = R"(
#version 330 core
layout (location = 0) in vec3 aPosition;
layout (location = 1) in vec3 aNormal;
layout (location = 2) in vec2 aTexCoord;

uniform mat4 uModel;
uniform mat3 uNormalMatrix;
uniform mat4 uView;
uniform mat4 uProjection;

// Texture coordinate mode: mesh UVs scaled by uTexScale, or box mapping
uniform bool  uBoxMapping;
uniform vec3  uPartSize;       // world-space size of the part (box mapping)
uniform float uRepeatsPerUnit; // texture repeats per world unit (box mapping)
uniform vec2  uTexScale;       // UV multiplier (mesh UV mode)

out vec3 vWorldNormal;
out vec2 vTexCoord;

void main() {
    gl_Position  = uProjection * uView * uModel * vec4(aPosition, 1.0);
    vWorldNormal = normalize(uNormalMatrix * aNormal);

    if (uBoxMapping) {
        // Project the face onto the two axes it spans, measured in world
        // units, so the texture keeps a constant size on any box.
        vec3 sized = aPosition * uPartSize * uRepeatsPerUnit;
        vec3 n = abs(aNormal);
        if (n.x > 0.5)      vTexCoord = sized.zy;   // side faces facing +-X
        else if (n.z > 0.5) vTexCoord = sized.xy;   // side faces facing +-Z
        else                vTexCoord = sized.xz;   // top and bottom faces
    } else {
        vTexCoord = aTexCoord * uTexScale;
    }
}
)";

const char *FRAGMENT_SHADER_SOURCE = R"(
#version 330 core
in vec3 vWorldNormal;
in vec2 vTexCoord;

uniform sampler2D uTexture;
uniform vec3 uTint;
uniform vec3 uSunDirection;
uniform vec3 uSunColor;
uniform vec3 uSkyAmbient;
uniform vec3 uGroundAmbient;

out vec4 FragColor;

void main() {
    vec3 normal = normalize(vWorldNormal);

    // Hemisphere ambient: upward faces catch sky light, downward faces
    // catch bounce light from the ground.
    vec3 ambient = mix(uGroundAmbient, uSkyAmbient, normal.y * 0.5 + 0.5);
    float diffuse = max(dot(normal, normalize(uSunDirection)), 0.0);

    vec3 albedo = texture(uTexture, vTexCoord).rgb * uTint;
    FragColor = vec4(albedo * (ambient + diffuse * uSunColor), 1.0);
}
)";

