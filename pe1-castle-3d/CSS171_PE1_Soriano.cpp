// Compile one shader stage; returns 0 and prints the log on failure
GLuint compileShader(GLenum stage, const char *source, const char *stageName) {
    GLuint shader = glCreateShader(stage);
    glShaderSource(shader, 1, &source, nullptr);
    glCompileShader(shader);

    GLint success = GL_FALSE;
    glGetShaderiv(shader, GL_COMPILE_STATUS, &success);
    if (!success) {
        char log[1024];
        glGetShaderInfoLog(shader, sizeof(log), nullptr, log);
        std::cerr << stageName << " shader compilation failed:\n" << log << "\n";
        glDeleteShader(shader);
        return 0;
    }
    return shader;
}

// Compile and link the shader program; returns 0 on failure
GLuint createShaderProgram() {
    GLuint vertexShader   = compileShader(GL_VERTEX_SHADER, VERTEX_SHADER_SOURCE, "Vertex");
    GLuint fragmentShader = compileShader(GL_FRAGMENT_SHADER, FRAGMENT_SHADER_SOURCE, "Fragment");
    if (vertexShader == 0 || fragmentShader == 0) {
        glDeleteShader(vertexShader);
        glDeleteShader(fragmentShader);
        return 0;
    }

    GLuint program = glCreateProgram();
    glAttachShader(program, vertexShader);
    glAttachShader(program, fragmentShader);
    glLinkProgram(program);
    glDeleteShader(vertexShader);
    glDeleteShader(fragmentShader);

    GLint success = GL_FALSE;
    glGetProgramiv(program, GL_LINK_STATUS, &success);
    if (!success) {
        char log[1024];
        glGetProgramInfoLog(program, sizeof(log), nullptr, log);
        std::cerr << "Shader program linking failed:\n" << log << "\n";
        glDeleteProgram(program);
        return 0;
    }
    return program;
}

// Uniform locations looked up once after linking
struct Uniforms {
    GLint model, normalMatrix, view, projection;
    GLint boxMapping, partSize, repeatsPerUnit, texScale;
    GLint texture, tint, sunDirection, sunColor, skyAmbient, groundAmbient;
};

Uniforms findUniforms(GLuint program) {
    Uniforms u;
    u.model          = glGetUniformLocation(program, "uModel");
    u.normalMatrix   = glGetUniformLocation(program, "uNormalMatrix");
    u.view           = glGetUniformLocation(program, "uView");
    u.projection     = glGetUniformLocation(program, "uProjection");
    u.boxMapping     = glGetUniformLocation(program, "uBoxMapping");
    u.partSize       = glGetUniformLocation(program, "uPartSize");
    u.repeatsPerUnit = glGetUniformLocation(program, "uRepeatsPerUnit");
    u.texScale       = glGetUniformLocation(program, "uTexScale");
    u.texture        = glGetUniformLocation(program, "uTexture");
    u.tint           = glGetUniformLocation(program, "uTint");
    u.sunDirection   = glGetUniformLocation(program, "uSunDirection");
    u.sunColor       = glGetUniformLocation(program, "uSunColor");
    u.skyAmbient     = glGetUniformLocation(program, "uSkyAmbient");
    u.groundAmbient  = glGetUniformLocation(program, "uGroundAmbient");
    return u;
}

// ------------------------------------------------------------------------------
// Rendering
// ------------------------------------------------------------------------------

// Draw every part under the animated root (turntable) transform
void drawCastle(const std::vector<Part> &parts, const Mesh meshes[], const GLuint textures[],
                const Uniforms &u, const glm::mat4 &root) {
    for (const Part &part : parts) {
        const Mesh &mesh = meshes[(int)part.shape];
        glm::mat4 model = root * part.transform;
        // Inverse-transpose keeps normals perpendicular under non-uniform scale
        glm::mat3 normalMatrix = glm::transpose(glm::inverse(glm::mat3(model)));

        glUniformMatrix4fv(u.model, 1, GL_FALSE, glm::value_ptr(model));
        glUniformMatrix3fv(u.normalMatrix, 1, GL_FALSE, glm::value_ptr(normalMatrix));
        glUniform1i(u.boxMapping, part.boxMapping ? 1 : 0);
        glUniform3fv(u.partSize, 1, glm::value_ptr(part.size));
        glUniform2fv(u.texScale, 1, glm::value_ptr(part.texScale));
        glUniform3fv(u.tint, 1, glm::value_ptr(part.tint));
        glBindTexture(GL_TEXTURE_2D, textures[part.texture]);

        glBindVertexArray(mesh.vao);
        glDrawElements(GL_TRIANGLES, mesh.indexCount, GL_UNSIGNED_INT, (void *)0);
    }
    glBindVertexArray(0);
}

// ------------------------------------------------------------------------------
// Window callbacks
// ------------------------------------------------------------------------------

void framebufferSizeCallback(GLFWwindow *, int width, int height) {
    glViewport(0, 0, width, height);
}

void glfwErrorCallback(int code, const char *description) {
    std::cerr << "GLFW error " << code << ": " << description << "\n";
}

void processInput(GLFWwindow *window) {
    if (glfwGetKey(window, GLFW_KEY_ESCAPE) == GLFW_PRESS) {
        glfwSetWindowShouldClose(window, GLFW_TRUE);
    }
}

// ------------------------------------------------------------------------------
// Main
// ------------------------------------------------------------------------------

int main() {
    glfwSetErrorCallback(glfwErrorCallback);
    if (!glfwInit()) {
        std::cerr << "Failed to initialize GLFW\n";
        return EXIT_FAILURE;
    }

    // Request an OpenGL 3.3 core profile context with 4x multisampling
    glfwWindowHint(GLFW_CONTEXT_VERSION_MAJOR, 3);
    glfwWindowHint(GLFW_CONTEXT_VERSION_MINOR, 3);
    glfwWindowHint(GLFW_OPENGL_PROFILE, GLFW_OPENGL_CORE_PROFILE);
    glfwWindowHint(GLFW_SAMPLES, 4);
#ifdef __APPLE__
    glfwWindowHint(GLFW_OPENGL_FORWARD_COMPAT, GL_TRUE);
#endif

    GLFWwindow *window = glfwCreateWindow(WINDOW_WIDTH, WINDOW_HEIGHT, WINDOW_TITLE, nullptr, nullptr);
    if (window == nullptr) {
        std::cerr << "Failed to create GLFW window\n";
        glfwTerminate();
        return EXIT_FAILURE;
    }
    glfwMakeContextCurrent(window);
    glfwSetFramebufferSizeCallback(window, framebufferSizeCallback);
    glfwSwapInterval(1);

    if (!gladLoadGLLoader((GLADloadproc)glfwGetProcAddress)) {
        std::cerr << "Failed to initialize GLAD\n";
        glfwDestroyWindow(window);
        glfwTerminate();
        return EXIT_FAILURE;
    }

    GLuint program = createShaderProgram();
    GLuint textures[TEXTURE_COUNT] = {};
    bool texturesLoaded = true;
    for (int i = 0; i < TEXTURE_COUNT && program != 0; ++i) {
        textures[i] = loadTexture(TEXTURE_FILES[i]);
        texturesLoaded = texturesLoaded && textures[i] != 0;
    }
    if (program == 0 || !texturesLoaded) {
        glDeleteTextures(TEXTURE_COUNT, textures);
        glDeleteProgram(program);
        glfwDestroyWindow(window);
        glfwTerminate();
        return EXIT_FAILURE;
    }

    // Indexed by Shape: Box, Cylinder, Cone
    Mesh meshes[] = { createBoxMesh(), createCylinderMesh(ROUND_SEGMENTS), createConeMesh(ROUND_SEGMENTS) };
    const std::vector<Part> parts = buildCastle();

    glEnable(GL_DEPTH_TEST);
    glEnable(GL_CULL_FACE);
    glEnable(GL_MULTISAMPLE);

    // Camera and lighting never change, so their uniforms are set once
    glUseProgram(program);
    Uniforms u = findUniforms(program);
    glm::mat4 view = glm::lookAt(CAMERA_POSITION, CAMERA_TARGET, CAMERA_UP);
    glUniformMatrix4fv(u.view, 1, GL_FALSE, glm::value_ptr(view));
    glm::vec3 sunDirection = glm::normalize(SUN_DIRECTION);
    glUniform3fv(u.sunDirection, 1, glm::value_ptr(sunDirection));
    glUniform3fv(u.sunColor, 1, glm::value_ptr(SUN_COLOR));
    glUniform3fv(u.skyAmbient, 1, glm::value_ptr(SKY_AMBIENT));
    glUniform3fv(u.groundAmbient, 1, glm::value_ptr(GROUND_AMBIENT));
    glUniform1f(u.repeatsPerUnit, TEXTURE_REPEATS_PER_UNIT);
    glUniform1i(u.texture, 0);
    glActiveTexture(GL_TEXTURE0);

    while (!glfwWindowShouldClose(window)) {
        processInput(window);

        // Rebuild the projection each frame so resizing keeps the castle
        // centered and undistorted; skip rendering while minimized.
        int framebufferWidth = 0;
        int framebufferHeight = 0;
        glfwGetFramebufferSize(window, &framebufferWidth, &framebufferHeight);
        if (framebufferWidth > 0 && framebufferHeight > 0) {
            float aspect = (float)framebufferWidth / (float)framebufferHeight;
            glm::mat4 projection = glm::perspective(glm::radians(FIELD_OF_VIEW_DEG), aspect,
                                                    NEAR_PLANE, FAR_PLANE);
            glUniformMatrix4fv(u.projection, 1, GL_FALSE, glm::value_ptr(projection));

            glClearColor(SKY_COLOR.r, SKY_COLOR.g, SKY_COLOR.b, 1.0f);
            glClear(GL_COLOR_BUFFER_BIT | GL_DEPTH_BUFFER_BIT);

            // Root of the hierarchy: the turntable spin applied to every part
            float angle = glm::radians(ROTATION_DEGREES_PER_SECOND * (float)glfwGetTime());
            glm::mat4 root = glm::rotate(glm::mat4(1.0f), angle, glm::vec3(0, 1, 0));
            drawCastle(parts, meshes, textures, u, root);
        }

        glfwSwapBuffers(window);
        glfwPollEvents();
    }

    for (Mesh &mesh : meshes) {
        deleteMesh(mesh);
    }
    glDeleteTextures(TEXTURE_COUNT, textures);
    glDeleteProgram(program);
    glfwDestroyWindow(window);
    glfwTerminate();
    return EXIT_SUCCESS;
}
